// xml_dtd.h
// The DTD: what the declarations of a document type declaration and of its internal and external subsets declare -
//  the element types and their content models, the attributes of each element type, the entities and the notations -
//  and the parser which reads them.
// 19NOV2026
//
// xml_dtd< t_TyChar >: the declarations. Everything is copied into it: it doesn't refer to the text it was read from.
// xml_dtd_parser< t_TyChar >: reads declarations into an xml_dtd. The parsing itself is done by the parser generated by
//  pgen from the productions of the specification ( xmlpgen_dtd.cpp, _xmlpdtd.h ) with the DTD DFAs of the lexical
//  analyzer. This is the "handler" of that parser: it has a method for each production which declares something and
//  the method has the values of the symbols of the production. Those methods are named for the productions.
//
// What is done here beyond the grammar:
//  - The replacement text of an internal entity is made from its literal value as the specification says ( 4.5 ):
//    character references are replaced, parameter entity references are replaced and general entity references are
//    left as they are.
//  - A reference to a parameter entity between declarations [28a] is replaced: the replacement text of an internal
//    parameter entity is itself parsed as declarations. An external parameter entity is not read ( there is nothing here
//    yet which reads external entities ): as the specification requires of a processor which doesn't read one, the entity
//    and attribute-list declarations after the reference are then not processed - see FStoppedProcessingDeclarations().
//  - The first declaration of an entity and of an attribute of an element type is the one which binds.
//  - Well-formedness constraints: a parameter entity reference may not be within a declaration in the internal subset
//    and a parameter entity may not contain itself. These throw. A parameter entity must be declared before it is
//    referenced: that is a well-formedness constraint only for a document which is declared to be standalone - see
//    SetStandalone() - and otherwise a validity constraint ( 4.1: Entity Declared ).
//  - Validity constraints which can be seen in the declarations alone - an element type or a notation declared twice,
//    the same name twice in mixed content - are recorded and don't throw: see RgValidityErrors().
// What isn't done yet: reading the external subset and external parameter entities from where they are, references to
//  parameter entities within declarations ( external subset only ), and validating a document.

