// xml_dtd: The declarations of a document type.
template < class t_TyChar >
class xml_dtd
{
  typedef xml_dtd _TyThis;
public:
  typedef t_TyChar _TyChar;
  typedef basic_string< _TyChar > _TyStdStr;
  typedef basic_string_view< _TyChar > _TyStrView;
  typedef xml_dtd_element< _TyChar > _TyElement;
  typedef xml_dtd_attdef< _TyChar > _TyAttDef;
  typedef xml_dtd_entity< _TyChar > _TyEntity;
  typedef xml_dtd_notation< _TyChar > _TyNotation;
  typedef xml_dtd_external_id< _TyChar > _TyExternalId;
  typedef map< _TyStdStr, _TyElement, less<> > _TyMapElements;
  typedef map< _TyStdStr, vector< _TyAttDef >, less<> > _TyMapAttLists; // By element type: the attributes in the order declared.
  typedef map< _TyStdStr, _TyEntity, less<> > _TyMapEntities;
  typedef map< _TyStdStr, _TyNotation, less<> > _TyMapNotations;

  // The document type declaration [28]:
  _TyStdStr m_strRootName; // The name of the document's element type.
  optional< _TyExternalId > m_optExternalId; // The external subset - if there is one.
  bool m_fHasInternalSubset{ false };

  _TyMapElements m_mapElements;
  _TyMapAttLists m_mapAttLists;
  _TyMapEntities m_mapGeneralEntities;
  _TyMapEntities m_mapParameterEntities;
  _TyMapNotations m_mapNotations;
  // The validity constraints which the declarations themselves don't meet - see the top of this file.
  vector< string > m_rgstrValidityErrors;
  // A reference to a parameter entity which wasn't read came before other declarations: the entity and attribute-list
  //  declarations after it were not processed ( 5.1 ).
  bool m_fStoppedProcessingDeclarations{ false };

  void Clear()
  {
    *this = _TyThis();
  }
  const _TyElement * PGetElement( _TyStrView _sv ) const
  {
    typename _TyMapElements::const_iterator cit = m_mapElements.find( _sv );
    return ( m_mapElements.end() == cit ) ? nullptr : &cit->second;
  }
  // The attributes declared for the element type - null if none.
  const vector< _TyAttDef > * PGetAttList( _TyStrView _svElement ) const
  {
    typename _TyMapAttLists::const_iterator cit = m_mapAttLists.find( _svElement );
    return ( m_mapAttLists.end() == cit ) ? nullptr : &cit->second;
  }
  const _TyAttDef * PGetAttDef( _TyStrView _svElement, _TyStrView _svAttribute ) const
  {
    const vector< _TyAttDef > * prgAttDefs = PGetAttList( _svElement );
    if ( !!prgAttDefs )
      for ( _TyAttDef const & rad : *prgAttDefs )
        if ( _TyStrView( rad.m_strName ) == _svAttribute )
          return &rad;
    return nullptr;
  }
  const _TyEntity * PGetGeneralEntity( _TyStrView _sv ) const
  {
    typename _TyMapEntities::const_iterator cit = m_mapGeneralEntities.find( _sv );
    return ( m_mapGeneralEntities.end() == cit ) ? nullptr : &cit->second;
  }
  const _TyEntity * PGetParameterEntity( _TyStrView _sv ) const
  {
    typename _TyMapEntities::const_iterator cit = m_mapParameterEntities.find( _sv );
    return ( m_mapParameterEntities.end() == cit ) ? nullptr : &cit->second;
  }
  const _TyNotation * PGetNotation( _TyStrView _sv ) const
  {
    typename _TyMapNotations::const_iterator cit = m_mapNotations.find( _sv );
    return ( m_mapNotations.end() == cit ) ? nullptr : &cit->second;
  }

  // The text which a reference to the general entity stands for - when it stands for text alone.
  // A reference to an internal entity is replaced by its replacement text, which is then itself read as content ( 4.4.2 ):
  //  the character references and the references to entities within it are replaced in turn. We do that here, once,
  //  for an entity whose replacement text - and that of the entities it refers to - has no markup: no '<'. Such an entity
  //  is text wherever it is referenced.
  // Return false if it isn't: the entity is not declared, is external or unparsed, has markup in its replacement text,
  //  refers to itself or its replacement text isn't well formed as content.
  bool FGetGeneralEntityText( _TyStrView _svName, _TyStdStr & _rstrText ) const
  {
    _rstrText.clear();
    vector< _TyStrView > rgsvActive;
    return exdeOk == _EExpandGeneralEntity( _svName, _rstrText, rgsvActive, false );
  }
  // The normalized value of an attribute from its literal - what is between the quotes - 3.3.3:
  //  a character reference is the character, a reference to an entity is the replacement text of the entity treated in
  //  the same way, and a white space character ( which isn't from a character reference ) is a space. Then, unless the
  //  type of the attribute is CDATA, leading and trailing spaces are removed and spaces in a row are one space.
  // The well-formedness constraints are those of 3.1: the entities must be declared, may not be external and may not
  //  have a '<' in their replacement text.
  EXmlDtdExpand EGetAttributeValueText( _TyStrView _svLiteral, EXmlDtdAttType _eType, _TyStdStr & _rstrValue ) const
  {
    _rstrValue.clear();
    vector< _TyStrView > rgsvActive;
    const EXmlDtdExpand exde = _EExpandText( _svLiteral, _rstrValue, rgsvActive, true );
    if ( ( exdeOk != exde ) || ( exdatCDATA == _eType ) )
      return exde;
    _TyStdStr strNormalized;
    for ( _TyChar ch : _rstrValue )
    {
      if ( ( _TyChar( ' ' ) == ch ) && ( strNormalized.empty() || ( _TyChar( ' ' ) == strNormalized.back() ) ) )
        continue;
      strNormalized += ch;
    }
    if ( !strNormalized.empty() && ( _TyChar( ' ' ) == strNormalized.back() ) )
      strNormalized.pop_back();
    _rstrValue.swap( strNormalized );
    return exdeOk;
  }
  // Add the general entities which stand for text alone to the map of entity name to text - that of the lexical
  //  analyzer's user object ( xml_user_obj<>::GetEntityMap() ), with which references in character data and in the
  //  values of attributes are replaced. An entity which is in the map already is left as it is - so the predefined
  //  entities are what they are whatever is declared ( 4.6 ).
  // Those which don't stand for text alone are not added: a reference to one is then to an unknown entity.
  template < class t_TyEntityMap >
  void AddGeneralEntitiesTo( t_TyEntityMap & _rmap ) const
  {
    _TyStdStr strText;
    for ( typename _TyMapEntities::value_type const & rvt : m_mapGeneralEntities )
    {
      if ( ( _rmap.end() == _rmap.find( rvt.first ) ) && FGetGeneralEntityText( rvt.first, strText ) )
        _rmap.emplace( rvt.first, strText );
    }
  }
// Names and name tokens - [4], [4a], [5], [7]:
  static bool FIsNameStartChar( char32_t _ch )
  {
    return  ( U':' == _ch ) || ( ( _ch >= U'A' ) && ( _ch <= U'Z' ) ) || ( U'_' == _ch ) || ( ( _ch >= U'a' ) && ( _ch <= U'z' ) ) ||
            ( ( _ch >= 0xC0 ) && ( _ch <= 0xD6 ) ) || ( ( _ch >= 0xD8 ) && ( _ch <= 0xF6 ) ) || ( ( _ch >= 0xF8 ) && ( _ch <= 0x2FF ) ) ||
            ( ( _ch >= 0x370 ) && ( _ch <= 0x37D ) ) || ( ( _ch >= 0x37F ) && ( _ch <= 0x1FFF ) ) || ( ( _ch >= 0x200C ) && ( _ch <= 0x200D ) ) ||
            ( ( _ch >= 0x2070 ) && ( _ch <= 0x218F ) ) || ( ( _ch >= 0x2C00 ) && ( _ch <= 0x2FEF ) ) || ( ( _ch >= 0x3001 ) && ( _ch <= 0xD7FF ) ) ||
            ( ( _ch >= 0xF900 ) && ( _ch <= 0xFDCF ) ) || ( ( _ch >= 0xFDF0 ) && ( _ch <= 0xFFFD ) ) || ( ( _ch >= 0x10000 ) && ( _ch <= 0xEFFFF ) );
  }
  static bool FIsNameChar( char32_t _ch )
  {
    return  FIsNameStartChar( _ch ) || ( U'-' == _ch ) || ( U'.' == _ch ) || ( ( _ch >= U'0' ) && ( _ch <= U'9' ) ) || ( 0xB7 == _ch ) ||
            ( ( _ch >= 0x300 ) && ( _ch <= 0x36F ) ) || ( ( _ch >= 0x203F ) && ( _ch <= 0x2040 ) );
  }
  // _fName: a Name [5] - which begins as one must - and otherwise an Nmtoken [7].
  static bool FIsNmtoken( _TyStrView _sv, bool _fName = false )
  {
    if ( _sv.empty() )
      return false;
    // Most are ASCII: only one which isn't is converted.
    bool fAscii = true;
    for ( _TyChar ch : _sv )
    {
      if ( (make_unsigned_t< _TyChar >)ch >= 0x80 )
      {
        fAscii = false;
        break;
      }
    }
    if ( fAscii )
    {
      if ( _fName && !FIsNameStartChar( char32_t( _sv.front() ) ) )
        return false;
      for ( _TyChar ch : _sv )
        if ( !FIsNameChar( char32_t( ch ) ) )
          return false;
      return true;
    }
    basic_string< char32_t > str32;
    ConvertString( str32, _sv );
    if ( str32.empty() || ( _fName && !FIsNameStartChar( str32.front() ) ) )
      return false;
    for ( char32_t ch : str32 )
      if ( !FIsNameChar( ch ) )
        return false;
    return true;
  }
  static bool FIsName( _TyStrView _sv )
  {
    return FIsNmtoken( _sv, true );
  }
  // Whether a normalized value is one or more Names ( or Nmtokens ) with a space between each [6], [8].
  static bool FAreNmtokens( _TyStrView _sv, bool _fNames = false )
  {
    if ( _sv.empty() )
      return false;
    for ( ; ; )
    {
      const size_t knPosSpace = _sv.find( _TyChar( ' ' ) );
      if ( !FIsNmtoken( _sv.substr( 0, knPosSpace ), _fNames ) )
        return false;
      if ( _TyStrView::npos == knPosSpace )
        return true;
      _sv.remove_prefix( knPosSpace + 1 );
    }
  }

  // The validity constraints on the declarations which can be checked only once all of the declarations have been read:
  //  what one of them refers to may be declared after it. What isn't met is added to m_rgstrValidityErrors.
  //  - VC: ID Attribute Default [56]: an attribute of type ID is declared #IMPLIED or #REQUIRED.
  //  - VC: One ID per Element Type [56] and VC: One Notation Per Element Type [58].
  //  - VC: No Notation on Empty Element [58].
  //  - VC: Notation Attributes [58]: the notations of an attribute of type NOTATION are declared.
  //  - VC: Attribute Default Value Syntactically Correct [60]: a default value is as the type of its attribute requires.
  //  - VC: Notation Declared [76]: the notation of an unparsed entity is declared.
  // xml_dtd_parser calls this at the end of the document type declaration.
  void CheckDeclarations()
  {
    auto lambdaError = [this]( const char * _pszFormat, _TyStrView _svFirst, _TyStrView _svSecond = _TyStrView(), _TyStrView _svThird = _TyStrView() )
    {
      // ( An empty view is not given to the conversion: it may have no characters to point to. )
      auto lambdaNarrow = []( _TyStrView _sv ) { return _sv.empty() ? string() : StrConvertString< char >( _sv ); };
      string str;
      PrintfStdStr( str, _pszFormat, lambdaNarrow( _svFirst ).c_str(), lambdaNarrow( _svSecond ).c_str(), lambdaNarrow( _svThird ).c_str() );
      m_rgstrValidityErrors.push_back( std::move( str ) );
    };
    for ( typename _TyMapAttLists::value_type const & rvtAttList : m_mapAttLists )
    {
      const _TyStdStr & rstrElement = rvtAttList.first;
      size_t nIds = 0, nNotations = 0;
      for ( _TyAttDef const & rad : rvtAttList.second )
      {
        if ( exdatID == rad.m_eType )
        {
          if ( 2 == ++nIds )
            lambdaError( "The element type [%s] has more than one attribute of type ID.", rstrElement );
          if ( ( exdadImplied != rad.m_eDefault ) && ( exdadRequired != rad.m_eDefault ) )
            lambdaError( "The attribute [%s] of the element type [%s] is of type ID and is not declared #IMPLIED or #REQUIRED.", rad.m_strName, rstrElement );
        }
        if ( exdatNOTATION == rad.m_eType )
        {
          if ( 2 == ++nNotations )
            lambdaError( "The element type [%s] has more than one attribute of type NOTATION.", rstrElement );
          const _TyElement * pElement = PGetElement( rstrElement );
          if ( !!pElement && ( exdcEmpty == pElement->m_eContent ) )
            lambdaError( "The attribute [%s] of the element type [%s] is of type NOTATION and the element type is declared EMPTY.", rad.m_strName, rstrElement );
          for ( _TyStdStr const & rstrNotation : rad.m_rgstrEnumeration )
            if ( !PGetNotation( rstrNotation ) )
              lambdaError( "The notation [%s] of the attribute [%s] of the element type [%s] is not declared.", rstrNotation, rad.m_strName, rstrElement );
        }
        if ( !rad.m_fHasDefaultValue )
          continue;
        // Only what the value must look like: whether what it names is there is asked of a tag which has the value.
        bool fSyntacticallyCorrect = true;
        const _TyStrView svValue( rad.m_strDefaultValue );
        switch( rad.m_eType )
        {
          case exdatID:
          case exdatIDREF:
          case exdatENTITY:
            fSyntacticallyCorrect = FIsName( svValue );
          break;
          case exdatIDREFS:
          case exdatENTITIES:
            fSyntacticallyCorrect = FAreNmtokens( svValue, true );
          break;
          case exdatNMTOKEN:
            fSyntacticallyCorrect = FIsNmtoken( svValue );
          break;
          case exdatNMTOKENS:
            fSyntacticallyCorrect = FAreNmtokens( svValue );
          break;
          case exdatNOTATION:
          case exdatEnumeration:
            fSyntacticallyCorrect = ( rad.m_rgstrEnumeration.end() != std::find( rad.m_rgstrEnumeration.begin(), rad.m_rgstrEnumeration.end(), rad.m_strDefaultValue ) );
          break;
          default:
          break;
        }
        if ( !fSyntacticallyCorrect )
          lambdaError( "The default value [%s] of the attribute [%s] of the element type [%s] is not as the type of the attribute requires.", svValue, rad.m_strName, rstrElement );
      }
    }
    for ( typename _TyMapEntities::value_type const & rvtEntity : m_mapGeneralEntities )
    {
      if ( rvtEntity.second.FIsUnparsed() && !PGetNotation( rvtEntity.second.m_strNotation ) )
        lambdaError( "The notation [%s] of the unparsed entity [%s] is not declared.", rvtEntity.second.m_strNotation, rvtEntity.first );
    }
  }
protected:
  static bool _FIsName( _TyStrView _sv, const char * _psz )
  {
    for ( _TyChar ch : _sv )
    {
      if ( !*_psz || ( ch != _TyChar( *_psz++ ) ) )
        return false;
    }
    return !*_psz;
  }
  // The text for which a reference to the entity stands is added to _rstrText.
  // _fAttributeValue: within the value of an attribute: white space is a space.
  EXmlDtdExpand _EExpandGeneralEntity( _TyStrView _svName, _TyStdStr & _rstrText, vector< _TyStrView > & _rrgsvActive, bool _fAttributeValue ) const
  {
    // The predefined entities ( 4.6 ): as text they are their characters.
    static const struct { const char * m_pszName; char m_ch; } s_rgPredefined[] = { { "lt", '<' }, { "gt", '>' }, { "amp", '&' }, { "apos", '\'' }, { "quot", '"' } };
    for ( auto const & rPredefined : s_rgPredefined )
    {
      if ( _FIsName( _svName, rPredefined.m_pszName ) )
      {
        _rstrText += _TyChar( rPredefined.m_ch );
        return exdeOk;
      }
    }
    const _TyEntity * pentity = PGetGeneralEntity( _svName );
    if ( !pentity )
      return exdeNotDeclared;
    if ( !pentity->m_fInternal )
      return exdeExternal;
    if ( _rrgsvActive.end() != std::find( _rrgsvActive.begin(), _rrgsvActive.end(), _svName ) )
      return exdeRecursive; // WFC: No Recursion - an error only if it is referenced.
    _rrgsvActive.push_back( _svName );
    const EXmlDtdExpand exde = _EExpandText( pentity->m_strValue, _rstrText, _rrgsvActive, _fAttributeValue );
    _rrgsvActive.pop_back();
    return exde;
  }
  // The text - the replacement text of an entity or the literal of the value of an attribute - with its references replaced.
  EXmlDtdExpand _EExpandText( _TyStrView svValue, _TyStdStr & _rstrText, vector< _TyStrView > & _rrgsvActive, bool _fAttributeValue ) const
  {
    for ( size_t n = 0; n < svValue.length(); ++n )
    {
      const _TyChar ch = svValue[ n ];
      if ( _TyChar( '<' ) == ch )
        return exdeMarkup;
      if ( _TyChar( '&' ) != ch )
      {
        if ( _fAttributeValue && ( ( _TyChar( 0x20 ) == ch ) || ( _TyChar( 0x0d ) == ch ) || ( _TyChar( 0x0a ) == ch ) || ( _TyChar( 0x09 ) == ch ) ) )
          _rstrText += _TyChar( ' ' );
        else
          _rstrText += ch;
        continue;
      }
      const size_t nEnd = svValue.find( _TyChar( ';' ), n );
      if ( ( _TyStrView::npos == nEnd ) || ( nEnd == n + 1 ) )
        return exdeNotWellFormed; // An '&' which isn't a reference.
      _TyStrView svReference = svValue.substr( n + 1, nEnd - n - 1 );
      n = nEnd;
      if ( _TyChar( '#' ) != svReference[0] )
      {
        const EXmlDtdExpand exde = _EExpandGeneralEntity( svReference, _rstrText, _rrgsvActive, _fAttributeValue );
        if ( exdeOk != exde )
          return exde;
        continue;
      }
      // A character reference: "#" digits or "#x" hex digits.
      const bool fHex = ( svReference.length() > 1 ) && ( _TyChar( 'x' ) == svReference[1] );
      svReference.remove_prefix( fHex ? 2 : 1 );
      char32_t ch32 = 0;
      if ( svReference.empty() )
        return exdeNotWellFormed;
      for ( _TyChar chDigit : svReference )
      {
        uint32_t nDigit;
        if ( ( chDigit >= _TyChar( '0' ) ) && ( chDigit <= _TyChar( '9' ) ) )
          nDigit = uint32_t( chDigit - _TyChar( '0' ) );
        else
        if ( fHex && ( chDigit >= _TyChar( 'a' ) ) && ( chDigit <= _TyChar( 'f' ) ) )
          nDigit = 10 + uint32_t( chDigit - _TyChar( 'a' ) );
        else
        if ( fHex && ( chDigit >= _TyChar( 'A' ) ) && ( chDigit <= _TyChar( 'F' ) ) )
          nDigit = 10 + uint32_t( chDigit - _TyChar( 'A' ) );
        else
          return exdeNotWellFormed;
        ch32 = ch32 * ( fHex ? 16 : 10 ) + nDigit;
        if ( ch32 > 0x10FFFF )
          return exdeNotWellFormed;
      }
      // [2] Char.
      if ( !( ( 0x9 == ch32 ) || ( 0xA == ch32 ) || ( 0xD == ch32 ) || ( ( ch32 >= 0x20 ) && ( ch32 <= 0xD7FF ) ) || ( ( ch32 >= 0xE000 ) && ( ch32 <= 0xFFFD ) ) || ( ch32 >= 0x10000 ) ) )
        return exdeNotWellFormed;
      _TyStdStr strChar;
      ConvertString( strChar, &ch32, 1 );
      _rstrText += strChar;
    }
    return exdeOk;
  }
};

