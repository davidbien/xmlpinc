// How often a particle of a content model may occur: nothing, '?', '*' or '+' - [47], [48].
enum EXmlDtdOccurrence : uint8_t
{
  exdoOnce,
  exdoOptional,
  exdoZeroOrMore,
  exdoOneOrMore,
  exdoEXmlDtdOccurrenceCount
};
enum EXmlDtdParticle : uint8_t
{
  exdpName, // An element type.
  exdpChoice, // [49]
  exdpSeq, // [50]
  exdpEXmlDtdParticleCount
};
// A content particle [48] - and the content model of an element type with element content [47]: a choice or a sequence.
template < class t_TyChar >
struct xml_dtd_content_particle
{
  typedef basic_string< t_TyChar > _TyStdStr;
  EXmlDtdParticle m_eParticle{ exdpName };
  EXmlDtdOccurrence m_eOccurrence{ exdoOnce };
  _TyStdStr m_strName; // The element type for exdpName.
  vector< xml_dtd_content_particle > m_rgChildren; // The particles of a choice or a sequence.
};
enum EXmlDtdContent : uint8_t
{
  exdcEmpty, // EMPTY
  exdcAny, // ANY
  exdcMixed, // [51]
  exdcChildren, // [47]
  exdcEXmlDtdContentCount
};
// An element type declaration [45].
template < class t_TyChar >
struct xml_dtd_element
{
  typedef basic_string< t_TyChar > _TyStdStr;
  _TyStdStr m_strName;
  EXmlDtdContent m_eContent{ exdcAny };
  vector< _TyStdStr > m_rgstrMixedNames; // exdcMixed: the element types which may occur among the character data.
  xml_dtd_content_particle< t_TyChar > m_cpChildren; // exdcChildren: the content model.
};
enum EXmlDtdAttType : uint8_t
{
  exdatCDATA, // [55]
  exdatID, // [56]
  exdatIDREF,
  exdatIDREFS,
  exdatENTITY,
  exdatENTITIES,
  exdatNMTOKEN,
  exdatNMTOKENS,
  exdatNOTATION, // [58]
  exdatEnumeration, // [59]
  exdatEXmlDtdAttTypeCount
};
enum EXmlDtdAttDefault : uint8_t
{
  exdadRequired, // #REQUIRED
  exdadImplied, // #IMPLIED
  exdadFixed, // #FIXED AttValue
  exdadDefault, // AttValue
  exdadEXmlDtdAttDefaultCount
};
// The definition of an attribute [53].
template < class t_TyChar >
struct xml_dtd_attdef
{
  typedef basic_string< t_TyChar > _TyStdStr;
  _TyStdStr m_strName;
  EXmlDtdAttType m_eType{ exdatCDATA };
  vector< _TyStdStr > m_rgstrEnumeration; // exdatNOTATION: the notations, exdatEnumeration: the name tokens.
  EXmlDtdAttDefault m_eDefault{ exdadImplied };
  // exdadFixed, exdadDefault: the value as it is written between the quotes - its references are not replaced and it isn't normalized.
  _TyStdStr m_strDefault;
  // exdadFixed, exdadDefault: the value which a tag without the attribute has for it ( 3.3.2 ): the default with its
  //  references replaced and normalized ( 3.3.3 ). m_fHasDefaultValue is false if there is no default - or if the default
  //  refers to an entity which isn't declared ( not valid - see xml_dtd<>::m_rgstrValidityErrors ): then there is no value to give.
  bool m_fHasDefaultValue{ false };
  _TyStdStr m_strDefaultValue;
};
// Why the text of an entity or the value of an attribute couldn't be made - see xml_dtd<>::EGetAttributeValueText().
enum EXmlDtdExpand : uint8_t
{
  exdeOk,
  exdeNotDeclared, // A reference to an entity which isn't declared.
  exdeExternal, // A reference to an external ( or unparsed ) entity.
  exdeMarkup, // A '<' in the replacement text of an entity.
  exdeRecursive, // An entity which refers to itself.
  exdeNotWellFormed, // An '&' which is not a reference, a character reference to what is not a character.
  exdeEXmlDtdExpandCount
};
// ExternalID [75] and PublicID [83].
template < class t_TyChar >
struct xml_dtd_external_id
{
  typedef basic_string< t_TyChar > _TyStdStr;
  optional< _TyStdStr > m_optstrPublic;
  optional< _TyStdStr > m_optstrSystem;
};
// An entity declaration [70]: general or parameter, internal or external, and an unparsed entity if it has a notation.
template < class t_TyChar >
struct xml_dtd_entity
{
  typedef basic_string< t_TyChar > _TyStdStr;
  _TyStdStr m_strName;
  bool m_fParameter{ false };
  bool m_fInternal{ true };
  _TyStdStr m_strValue; // Internal: the replacement text.
  xml_dtd_external_id< t_TyChar > m_externalId; // External.
  _TyStdStr m_strNotation; // An unparsed entity: the notation of its NDATA [76].
  bool m_fDeclaredExternally{ false }; // Declared in the external subset or in a parameter entity.
  bool FIsUnparsed() const
  {
    return !m_strNotation.empty();
  }
};
